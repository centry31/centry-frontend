/**
 * Форматирует смещение в минутах в человекочитаемый вид.
 *
 * Правила форматирования:
 *  - < 60 минут  → "{m} мин"
 *  - кратно 60   → "{h} ч"
 *  - кратно 1440 → "{d} дн" (где 1440 = 24 * 60)
 *  - иначе       → "{h} ч {m} мин"
 *
 * Особенности:
 *  - Функция рассчитывает часы и остаток минут через целочисленное деление и модуль.
 *  - Отрицательные значения не нормализуются (вернётся строка с отрицательными числами);
 *    при необходимости нормализуйте на уровне вызова (например, Math.abs(mins)).
 *
 * Примеры:
 *  formatOffset(5)        // "5 мин"
 *  formatOffset(60)       // "1 ч"
 *  formatOffset(90)       // "1 ч 30 мин"
 *  formatOffset(1440)     // "1 дн"
 *  formatOffset(1510)     // "25 ч 10 мин"
 */
export const formatMinutesOffset = (mins: number) => {
	if (mins < 60) return `${mins} мин`;
	if (mins % 1440 === 0) return `${mins / 1440} дн`;
	if (mins % 60 === 0) return `${mins / 60} ч`;

	const h = Math.floor(mins / 60);
	const m = mins % 60;
	return `${h} ч ${m} мин`;
};
